(function () {
    const nativeConfirm = window.confirm;
    const nativeAlert = window.alert;

    function _translateNative(message) {
        const raw = String(message === null || message === undefined ? '' : message);
        const base = _normSpace(raw);
        const dict = _srcDict();
        if (dict && dict[base] !== undefined) return dict[base];
        const list = NATIVE_TEXT_PATTERNS[_currentLang];
        if (list) {
            for (let i = 0; i < list.length; i++) {
                if (list[i][0].test(base)) return base.replace(list[i][0], list[i][1]);
            }
        }
        return raw;
    }

    window.confirm = function (message) {
        return nativeConfirm.call(window, _translateNative(message));
    };
    window.alert = function (message) {
        return nativeAlert.call(window, _translateNative(message));
    };
})();

function _translateTextNodes(root) {
    if (!root) return;
    const dict = _srcDict();
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            const p = node.parentNode;
            if (!p) return NodeFilter.FILTER_REJECT;
            const tag = p.nodeName;
            if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TEXTAREA' ||
                tag === 'CODE' || tag === 'PRE') {
                return NodeFilter.FILTER_REJECT;
            }
            return NodeFilter.FILTER_ACCEPT;
        }
    });
    const pending = [];
    let node;
    while ((node = walker.nextNode())) {
        const raw = node.nodeValue;
        if (!raw || !raw.trim()) continue;
        const memo = _srcTextMemo.get(node);
        if (memo && raw === memo.out) {
            if (!dict) pending.push([node, memo.src]);
            continue;
        }
        if (memo) _srcTextMemo.delete(node);
        if (!dict) continue;
        let base = _normSpace(raw);
        // 状态列是「⚠ Kernel boot needs extraction」「✓ Ready」这种：图标和文字在同一个
        // 文本节点里，先剥掉前缀图标再查表，命中后把图标补回去
        let mark = '';
        const mm = base.match(/^([^\p{L}\p{N}一-龥]{1,2}\s+)(.+)$/u);
        if (mm) {
            const rest = mm[2].trim();
            if (dict[rest] !== undefined || _patternTranslate(rest) !== null || _prefixTranslate(rest) !== null) {
                mark = mm[1];
                base = rest;
            }
        }
        // 可排序表头的文本是「Name ↕」这种：箭头由 sortIcon 直接拼在文本节点里，
        // 先把箭头剥掉再查表，命中后把箭头补回去
        let arrow = '';
        const am = base.match(/^(.+?)\s*([\u2195\u2191\u2193\u21c5\u25b2\u25bc])$/);
        if (am && dict[am[1].trim()] !== undefined) {
            base = am[1].trim();
            arrow = ' ' + am[2];
        }
        let hit = dict[base];
        if (hit === undefined) hit = _patternTranslate(base);
        if (hit === undefined || hit === null) hit = _prefixTranslate(base);
        if (hit === undefined || hit === null) continue;
        hit = mark + hit + arrow;
        let lead = raw.match(/^\s*/)[0];
        const trail = raw.match(/\s*$/)[0];
        // 译文以中文标点开头时丢掉原文的前导空格，免得出现「 ，」
        if (/^[，。：；、！？）】」》]/.test(hit)) lead = '';
        const out = lead + hit + trail;
        _srcTextMemo.set(node, { src: raw, out: out });
        if (raw !== out) pending.push([node, out]);
    }
    for (const item of pending) item[0].nodeValue = item[1];
}

function _translateAttrs(root) {
    if (!root || !root.querySelectorAll) return;
    const dict = _srcDict();
    const writes = [];
    root.querySelectorAll('[title],[placeholder],[aria-label]').forEach(el => {
        let memo = _srcAttrMemo.get(el);
        if (!memo) {
            memo = {};
            _srcAttrMemo.set(el, memo);
        }
        for (const attr of _SRC_ATTRS) {
            if (!el.hasAttribute(attr)) continue;
            const raw = el.getAttribute(attr);
            if (raw === null) continue;
            const m = memo[attr];
            if (m && raw === m.out) {
                if (!dict) writes.push([el, attr, m.src]);
                continue;
            }
            if (m) delete memo[attr];
            if (!dict) continue;
            const hit = dict[_normSpace(raw)];
            if (hit === undefined) continue;
            memo[attr] = { src: raw, out: hit };
            writes.push([el, attr, hit]);
        }
    });
    for (const w of writes) w[0].setAttribute(w[1], w[2]);
}

function _translateTitle() {
    if (_titleSrc === null) _titleSrc = document.title;
    const dict = _srcDict();
    if (!dict) {
        if (document.title !== _titleSrc) document.title = _titleSrc;
        return;
    }
    const hit = dict[_normSpace(_titleSrc)];
    if (hit !== undefined && document.title !== hit) document.title = hit;
}

// 每批 DOM 变动只翻译「变过的那几棵子树」。以前每次变动都从 document.body 全量
// 走一遍 TreeWalker，而下载页每秒刷新进度 —— 等于每秒扫一遍全表。
let _dirtyRoots = new Set();
const _DIRTY_FULL_THRESHOLD = 40;

function _markDirty(node) {
    if (!node) return;
    const el = node.nodeType === Node.TEXT_NODE ? node.parentNode : node;
    if (el && el.nodeType === Node.ELEMENT_NODE) _dirtyRoots.add(el);
}

function _applyAll() {
    if (_applying || !document.body) return;
    _dirtyRoots = new Set();
    _applying = true;
    try {
        applyTranslations(document);
        _translateTextNodes(document.body);
        _translateAttrs(document);
        _translateTitle();
    } finally {
        _applying = false;
        if (_autoObserver) _autoObserver.takeRecords();
    }
}

function _applyDirty() {
    if (_applying || !document.body) return;
    const roots = _dirtyRoots;
    _dirtyRoots = new Set();
    // 整表重绘时逐个子树反而更贵，超过阈值就退回全量
    if (roots.size === 0 || roots.size > _DIRTY_FULL_THRESHOLD) {
        _applyAll();
        return;
    }
    _applying = true;
    try {
        roots.forEach(root => {
            const scope = root.parentElement || root;
            if (!scope || !scope.isConnected) return;
            applyTranslations(scope);
            _translateTextNodes(scope);
            _translateAttrs(scope);
        });
        _translateTitle();
    } finally {
        _applying = false;
        if (_autoObserver) _autoObserver.takeRecords();
    }
}

function _installAutoTranslate() {
    if (_autoObserver || typeof MutationObserver === 'undefined' || !document.body) return;
    _autoObserver = new MutationObserver((records) => {
        for (const r of records) _markDirty(r.target);
        if (_applying || _autoTimer) return;
        _autoTimer = setTimeout(() => {
            _autoTimer = null;
            _applyDirty();
        }, 30);
    });
    _autoObserver.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
        attributes: true,
        attributeFilter: _SRC_ATTRS
    });
}

const _COMMON_BUTTON_MAP = {
    'Cancel': 'common.cancel',
    'Save': 'common.save',
    'Close': 'common.close',
    'Delete': 'common.delete',
};

function applyTranslations(root) {
    root = root || document;

    root.querySelectorAll('button').forEach(b => {
        if (b.hasAttribute('data-i18n')) return;
        const key = _COMMON_BUTTON_MAP[b.textContent.trim()];
        if (key) b.setAttribute('data-i18n', key);
    });

    root.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        let lastText = null;
        for (let i = el.childNodes.length - 1; i >= 0; i--) {
            const n = el.childNodes[i];
            if (n.nodeType === Node.TEXT_NODE && n.nodeValue.trim()) {
                lastText = n;
                break;
            }
        }
        if (lastText) {
            const next = lastText.nodeValue.replace(/\S.*\S|\S/, text);
            if (lastText.nodeValue !== next) lastText.nodeValue = next;
        } else if (el.textContent !== text) {
            el.textContent = text;
        }
    });
    root.querySelectorAll('[data-i18n-title]').forEach(el => {
        const next = t(el.getAttribute('data-i18n-title'));
        if (el.title !== next) el.title = next;
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const next = t(el.getAttribute('data-i18n-placeholder'));
        if (el.placeholder !== next) el.placeholder = next;
    });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const next = t(el.getAttribute('data-i18n-aria-label'));
        if (el.getAttribute('aria-label') !== next) el.setAttribute('aria-label', next);
    });
}

function setLanguage(lang) {
    if (!TRANSLATIONS[lang]) lang = 'en-GB';
    _currentLang = lang;
    localStorage.setItem('bootimus_lang', lang);
    document.documentElement.lang = lang;
    ['lang-select', 'login-lang-select'].forEach(id => {
        const s = document.getElementById(id);
        if (s && s.value !== lang) s.value = lang;
    });
    _applyAll();
}

function currentLanguage() {
    return _currentLang;
}

function _populateLangSelect(sel) {
    if (!sel) return;
    sel.innerHTML = '';
    for (const l of I18N_LANGS) {
        const opt = document.createElement('option');
        opt.value = l.code;
        opt.textContent = (l.flag ? l.flag + '  ' : '') + l.name;
        if (l.code === _currentLang) opt.selected = true;
        sel.appendChild(opt);
    }
    sel.addEventListener('change', e => setLanguage(e.target.value));
}

function _initI18n() {
    _currentLang = _detectInitialLang();
    document.documentElement.lang = _currentLang;

    _populateLangSelect(document.getElementById('lang-select'));
    _populateLangSelect(document.getElementById('login-lang-select'));

    _applyAll();
    _installAutoTranslate();
}

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', _initI18n);
} else {
    _initI18n();
}
